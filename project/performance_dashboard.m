function fig = performance_dashboard(res_in, model_pkg_in)
%PERFORMANCE_DASHBOARD  Comprehensive Performance & Safety Evaluation Dashboard
%   Displays measurable safety, detection, estimation, control, and latency metrics
%   in a multi-panel visual interface with metric definitions and units.
%
%   Usage:
%       fig = performance_dashboard()                    % runs benchmark & displays
%       fig = performance_dashboard(res)                 % displays specific run results
%       fig = performance_dashboard(res, model_pkg)      % displays with ML package

if nargin < 1 || isempty(res_in)
    fprintf('Running quick head-on evaluation scenario for dashboard display...\n');
    res_in = UnifiedFlightRadar3D('head_on', struct('T', 40, 'viz', struct('enable', false)));
end

if nargin < 2 || isempty(model_pkg_in)
    if exist('ml_conflict_model.mat', 'file') == 2
        data = load('ml_conflict_model.mat', 'model_pkg');
        model_pkg_in = data.model_pkg;
    else
        fprintf('Training baseline ML models for dashboard...\n');
        model_pkg_in = ml_train_models();
    end
end

M = res_in.M;
W = res_in.W;
cfg = res_in.cfg;
m_rule = model_pkg_in.metrics.rule;
m_lr   = model_pkg_in.metrics.logistic;
m_rf   = model_pkg_in.metrics.random_forest;

% Color Palette (Deep Aerospace Dark Mode)
c_bg    = [0.03 0.05 0.08];
c_card  = [0.07 0.10 0.16];
c_card2 = [0.09 0.13 0.20];
c_cyan  = [0.15 0.85 1.00];
c_green = [0.15 0.95 0.55];
c_amber = [1.00 0.72 0.15];
c_red   = [1.00 0.30 0.30];
c_txt   = [0.90 0.95 1.00];
c_dim   = [0.50 0.65 0.78];

fig = figure('Name', 'Comprehensive Air Traffic Safety & AI Evaluation Dashboard', ...
    'NumberTitle', 'off', 'Color', c_bg, 'Position', [40 40 1560 900], 'MenuBar', 'none');

% Header Title Banner
pHead = uipanel('Parent', fig, 'Position', [0.01 0.93 0.98 0.065], ...
    'BackgroundColor', c_card, 'BorderType', 'line', 'HighlightColor', c_card2);

uicontrol('Parent', pHead, 'Style', 'text', 'String', 'AIR TRAFFIC CONFLICT PREDICTION & RESOLUTION EVALUATION DASHBOARD', ...
    'Units', 'normalized', 'Position', [0.02 0.45 0.60 0.50], 'ForegroundColor', c_cyan, ...
    'BackgroundColor', c_card, 'FontSize', 13, 'FontWeight', 'bold', 'HorizontalAlignment', 'left');

uicontrol('Parent', pHead, 'Style', 'text', ...
    'String', sprintf('Scenario: %s | Duration: %.1fs | Seed: %d | Status: %s', ...
    upper(cfg.scenario), M.T, cfg.seed, tern_local(M.pass, 'PASS (SAFE)', 'SAFETY ALERT')), ...
    'Units', 'normalized', 'Position', [0.02 0.05 0.60 0.40], 'ForegroundColor', c_dim, ...
    'BackgroundColor', c_card, 'FontSize', 9.5, 'HorizontalAlignment', 'left');

uicontrol('Parent', pHead, 'Style', 'text', 'String', 'RESEARCH SIMULATION PROTOTYPE  -  DEMO / SIMULATED DATA', ...
    'Units', 'normalized', 'Position', [0.65 0.30 0.33 0.45], 'ForegroundColor', c_amber, ...
    'BackgroundColor', c_card, 'FontSize', 10, 'FontWeight', 'bold', 'HorizontalAlignment', 'right');

% ==================== 1. TOP KPI SUMMARY TILES ====================
kpi_x = linspace(0.01, 0.99, 7);
kpi_w = (kpi_x(2) - kpi_x(1)) * 0.96;
kpi_y = 0.825; kpi_h = 0.095;

create_kpi_card(fig, [kpi_x(1) kpi_y kpi_w kpi_h], 'AIRCRAFT / ENCOUNTERS', ...
    sprintf('%d / %d', M.na, M.na*(M.na-1)/2), 'Total traffic simulated', c_cyan, c_card, c_txt, c_dim);

create_kpi_card(fig, [kpi_x(2) kpi_y kpi_w kpi_h], 'MIN HORIZ SEPARATION', ...
    sprintf('%.0f m', M.minH), sprintf('Standard: %d m', cfg.sep.H), tern_local(M.minH >= cfg.sep.H, c_green, c_red), c_card, c_txt, c_dim);

create_kpi_card(fig, [kpi_x(3) kpi_y kpi_w kpi_h], 'LOSS OF SEPARATION', ...
    sprintf('%d', M.los_events), 'Safety boundary breaches', tern_local(M.los_events == 0, c_green, c_red), c_card, c_txt, c_dim);

create_kpi_card(fig, [kpi_x(4) kpi_y kpi_w kpi_h], 'RESOLVED / DETECTED', ...
    sprintf('%d / %d', M.resolved, M.conflicts), sprintf('Unresolved: %d', M.unresolved), c_green, c_card, c_txt, c_dim);

create_kpi_card(fig, [kpi_x(5) kpi_y kpi_w kpi_h], 'EKF POS RMSE', ...
    sprintf('%.2f m', mean(M.ekf_pos_rmse)), sprintf('Alt RMSE: %.2f m', mean(M.ekf_alt_rmse)), c_amber, c_card, c_txt, c_dim);

create_kpi_card(fig, [kpi_x(6) kpi_y kpi_w kpi_h], 'MPC MEAN LATENCY', ...
    sprintf('%.2f ms', 1e3*M.mpc_time_mean), sprintf('Fallbacks: %d / %d', M.mpc_fallbacks, M.mpc_calls), c_cyan, c_card, c_txt, c_dim);

% ==================== 2. LEFT PANEL: DETECTION & AI/ML METRICS ====================
pLeft = uipanel('Parent', fig, 'Position', [0.01 0.02 0.31 0.79], ...
    'BackgroundColor', c_card, 'BorderType', 'line', 'HighlightColor', c_card2);

uicontrol('Parent', pLeft, 'Style', 'text', 'String', 'AI/ML CONFLICT PREDICTION PERFORMANCE', ...
    'Units', 'normalized', 'Position', [0.04 0.94 0.92 0.04], 'ForegroundColor', c_cyan, ...
    'BackgroundColor', c_card, 'FontSize', 10.5, 'FontWeight', 'bold', 'HorizontalAlignment', 'left');

% Table of Classification Metrics
det_str = sprintf([ ...
    '------------------------------------------------------------\n' ...
    'METRIC                  RULE-BASED    LOGISTIC      RANDOM FOREST\n' ...
    '------------------------------------------------------------\n' ...
    'Accuracy                %5.1f %%      %5.1f %%      %5.1f %%\n' ...
    'Recall (Sensitivity)    %5.1f %%      %5.1f %%      %5.1f %%\n' ...
    'Precision (PPV)         %5.1f %%      %5.1f %%      %5.1f %%\n' ...
    'F1-Score                %6.3f        %6.3f        %6.3f\n' ...
    'False Alarm Rate (FAR)  %5.1f %%      %5.1f %%      %5.1f %%\n' ...
    'Specificity (TNR)       %5.1f %%      %5.1f %%      %5.1f %%\n' ...
    'Brier Calibration       %6.4f       %6.4f       %6.4f\n' ...
    'Area Under ROC (AUC)    %6.4f       %6.4f       %6.4f\n' ...
    'Lead Time (Mean)        %5.1f s      %5.1f s      %5.1f s\n' ...
    'Inference Latency       %5.1f us    %5.1f us    %5.1f us\n' ...
    '------------------------------------------------------------\n' ...
    'CONFUSION MATRIX (Test Set):\n' ...
    '  Rule-Based:    TP=%-3d  FP=%-3d  TN=%-3d  FN=%-3d\n' ...
    '  Logistic Reg:  TP=%-3d  FP=%-3d  TN=%-3d  FN=%-3d\n' ...
    '  Random Forest: TP=%-3d  FP=%-3d  TN=%-3d  FN=%-3d\n' ...
    '------------------------------------------------------------\n' ...
    'CURRENT ENCOUNTER DUAL-MONITOR STATUS:\n' ...
    '  Existing Rule Detector: %d conflict(s) flagged\n' ...
    '  Resolved Maneuvers:     %d tactical replans committed\n' ...
    '  Zone Intrusion Replans: %d detours computed\n' ...
    '  Zone Violations:        %d (ground truth)\n' ...
    '  Actuator Saturation %%:  thr %.1f%%  elev %.1f%%  ail %.1f%%\n'], ...
    100*m_rule.accuracy, 100*m_lr.accuracy, 100*m_rf.accuracy, ...
    100*m_rule.recall,   100*m_lr.recall,   100*m_rf.recall, ...
    100*m_rule.precision,100*m_lr.precision,100*m_rf.precision, ...
    m_rule.f1,           m_lr.f1,           m_rf.f1, ...
    100*m_rule.far,      100*m_lr.far,      100*m_rf.far, ...
    100*m_rule.specificity, 100*m_lr.specificity, 100*m_rf.specificity, ...
    m_rule.brier,        m_lr.brier,        m_rf.brier, ...
    m_rule.auc,          m_lr.auc,          m_rf.auc, ...
    m_rule.lead_mean,    m_lr.lead_mean,    m_rf.lead_mean, ...
    m_rule.latency_mean_us, m_lr.latency_mean_us, m_rf.latency_mean_us, ...
    m_rule.tp, m_rule.fp, m_rule.tn, m_rule.fn, ...
    m_lr.tp, m_lr.fp, m_lr.tn, m_lr.fn, ...
    m_rf.tp, m_rf.fp, m_rf.tn, m_rf.fn, ...
    M.conflicts, M.maneuvers, M.zone_replans, M.viol.zone, ...
    mean(M.sat_pct(1,:)), mean(M.sat_pct(2,:)), mean(M.sat_pct(3,:)));

uicontrol('Parent', pLeft, 'Style', 'text', 'String', det_str, ...
    'Units', 'normalized', 'Position', [0.03 0.02 0.94 0.90], 'ForegroundColor', c_txt, ...
    'BackgroundColor', c_card, 'FontSize', 8.5, 'FontName', 'Consolas', ...
    'HorizontalAlignment', 'left');

% ==================== 3. CENTER / RIGHT PLOTS (4 COMPARISON CHARTS) ====================
pCenter = uipanel('Parent', fig, 'Position', [0.33 0.28 0.66 0.53], ...
    'BackgroundColor', c_card, 'BorderType', 'line', 'HighlightColor', c_card2);

% Plot 1: Separation Timeline
ax1 = axes('Parent', pCenter, 'Position', [0.07 0.56 0.42 0.36], ...
    'Color', [0.04 0.06 0.10], 'XColor', c_dim, 'YColor', c_dim);
hold(ax1, 'on'); grid(ax1, 'on');
if isfield(W.L, 't') && W.nlog > 0
    t_log = W.L.t(1:W.nlog);
    minH_log = W.L.minH(1:W.nlog);
    plot(ax1, t_log, minH_log, 'Color', c_cyan, 'LineWidth', 1.8, 'DisplayName', 'Actual Min Separation');
    yline(ax1, cfg.sep.H, '--', 'Color', c_red, 'LineWidth', 1.5, 'DisplayName', sprintf('LoS Boundary (%dm)', cfg.sep.H));
    yline(ax1, cfg.sep.H * 1.1, ':', 'Color', c_amber, 'LineWidth', 1.2, 'DisplayName', 'Detection Threshold');
    xlabel(ax1, 'Time [s]', 'FontSize', 8.5, 'Color', c_dim);
    ylabel(ax1, 'Separation [m]', 'FontSize', 8.5, 'Color', c_dim);
    title(ax1, 'Pairwise Separation Timeline vs Safety Boundary', 'FontSize', 9.5, 'FontWeight', 'bold', 'Color', c_txt);
    legend(ax1, 'Location', 'northeast', 'TextColor', c_txt, 'Color', c_card, 'FontSize', 7.5);
    ylim(ax1, [0 max(max(minH_log)*1.1, cfg.sep.H * 2.5)]);
end

% Plot 2: Model Comparison Bar Chart
ax2 = axes('Parent', pCenter, 'Position', [0.55 0.56 0.42 0.36], ...
    'Color', [0.04 0.06 0.10], 'XColor', c_dim, 'YColor', c_dim);
vals = [ ...
    m_rule.accuracy, m_rule.recall, m_rule.precision, m_rule.f1, m_rule.far; ...
    m_lr.accuracy,   m_lr.recall,   m_lr.precision,   m_lr.f1,   m_lr.far; ...
    m_rf.accuracy,   m_rf.recall,   m_rf.precision,   m_rf.f1,   m_rf.far ...
] * 100;
b = bar(ax2, vals', 'grouped');
b(1).FaceColor = [0.45 0.50 0.55];
b(2).FaceColor = c_cyan;
b(3).FaceColor = c_green;
set(ax2, 'XTickLabel', {'Acc', 'Recall', 'Prec', 'F1', 'FAR'}, 'FontSize', 8.5);
ylabel(ax2, 'Score [%]', 'FontSize', 8.5, 'Color', c_dim);
title(ax2, 'AI/ML vs Rule Detector Classification Benchmark', 'FontSize', 9.5, 'FontWeight', 'bold', 'Color', c_txt);
legend(ax2, {'Rule-Based', 'Logistic Regression', 'Random Forest'}, 'Location', 'northeast', ...
    'TextColor', c_txt, 'Color', c_card, 'FontSize', 7.5);
grid(ax2, 'on'); ylim(ax2, [0 115]);

% Plot 3: Early Warning Lead Time Distribution
ax3 = axes('Parent', pCenter, 'Position', [0.07 0.10 0.42 0.35], ...
    'Color', [0.04 0.06 0.10], 'XColor', c_dim, 'YColor', c_dim);
models = {'Rule-Based', 'Logistic Reg', 'Random Forest'};
leads = [m_rule.lead_mean, m_lr.lead_mean, m_rf.lead_mean];
lead_errs = [m_rule.lead_std, m_lr.lead_std, m_rf.lead_std];
bar_h = bar(ax3, leads, 0.45, 'FaceColor', [0.2 0.65 0.95]);
hold(ax3, 'on');
errorbar(ax3, 1:3, leads, lead_errs, 'k.', 'Color', c_amber, 'LineWidth', 1.5, 'CapSize', 8);
set(ax3, 'XTickLabel', models, 'FontSize', 8.5);
ylabel(ax3, 'Lead Time [s]', 'FontSize', 8.5, 'Color', c_dim);
title(ax3, 'Conflict Prediction Lead Time Before CPA', 'FontSize', 9.5, 'FontWeight', 'bold', 'Color', c_txt);
grid(ax3, 'on');

% Plot 4: EKF Estimation Error & Tracking Error
ax4 = axes('Parent', pCenter, 'Position', [0.55 0.10 0.42 0.35], ...
    'Color', [0.04 0.06 0.10], 'XColor', c_dim, 'YColor', c_dim);
hold(ax4, 'on'); grid(ax4, 'on');
if isfield(W.L, 't') && W.nlog > 0
    t_log = W.L.t(1:W.nlog);
    for i = 1:min(M.na, 2)
        X_true = squeeze(W.L.x(:, 1:W.nlog, i));
        X_hat  = squeeze(W.L.xh(:, 1:W.nlog, i));
        pos_err = hypot(X_true(10,:) - X_hat(10,:), X_true(11,:) - X_hat(11,:));
        plot(ax4, t_log, pos_err, 'LineWidth', 1.3, 'DisplayName', sprintf('%s EKF Err', W.ac(i).name));
    end
    xlabel(ax4, 'Time [s]', 'FontSize', 8.5, 'Color', c_dim);
    ylabel(ax4, 'Position Error [m]', 'FontSize', 8.5, 'Color', c_dim);
    title(ax4, 'EKF State Estimation Error Timeline', 'FontSize', 9.5, 'FontWeight', 'bold', 'Color', c_txt);
    legend(ax4, 'Location', 'northeast', 'TextColor', c_txt, 'Color', c_card, 'FontSize', 7.5);
end

% ==================== 4. BOTTOM METRIC DEFINITIONS & GLOSSARY ====================
pBottom = uipanel('Parent', fig, 'Position', [0.33 0.02 0.66 0.25], ...
    'BackgroundColor', c_card, 'BorderType', 'line', 'HighlightColor', c_card2);

uicontrol('Parent', pBottom, 'Style', 'text', 'String', 'RIGOROUS METRIC DEFINITIONS, SAFETY CONSTRAINTS & UNITS', ...
    'Units', 'normalized', 'Position', [0.02 0.88 0.95 0.10], 'ForegroundColor', c_cyan, ...
    'BackgroundColor', c_card, 'FontSize', 9.5, 'FontWeight', 'bold', 'HorizontalAlignment', 'left');

def_text = sprintf([ ...
    '- Loss-of-Separation (LoS) Event: Horizontal distance < 1500 m AND vertical distance < 300 m simultaneously between any pair. [Standard ICAO cylinder]\n' ...
    '- Safety Violation: Any event violating flight envelope (alpha > 0.26 rad, bank > 60 deg, ground collision, or unreplanned restricted airspace intrusion).\n' ...
    '- Conflict Prediction Recall: TP / (TP + FN) * 100%%. Proportion of true impending conflicts successfully identified before separation loss.\n' ...
    '- Conflict Prediction Precision: TP / (TP + FP) * 100%%. Proportion of flagged warnings that correspond to genuine impending separation losses.\n' ...
    '- False Alarm Rate (FAR): FP / (FP + TN) * 100%%. Rate at which non-conflicting encounters are falsely flagged as hazardous.\n' ...
    '- Early Warning Lead Time: Seconds remaining until closest point of approach (CPA) when conflict is first detected. Higher lead time allows fuel-optimal replans.\n' ...
    '- Inference Latency: Execution wall time per pairwise feature extraction and model evaluation [microseconds]. Must remain < 5 ms for 50 Hz ATC cycles.\n' ...
    '- EKF Position RMSE: Root Mean Square Error sqrt(mean((x_true - x_ekf)^2 + (y_true - y_ekf)^2)) [meters] across state estimates.\n' ...
    '- IMPORTANT DISCLAIMER: The absence of an accident in a simulation does not constitute proof of aviation safety. This platform is an educational/research tool.']);

uicontrol('Parent', pBottom, 'Style', 'text', 'String', def_text, ...
    'Units', 'normalized', 'Position', [0.02 0.02 0.96 0.85], 'ForegroundColor', c_dim, ...
    'BackgroundColor', c_card, 'FontSize', 8.2, 'FontName', 'Arial', ...
    'HorizontalAlignment', 'left');

drawnow;
end

function create_kpi_card(fig, pos, title_str, val_str, sub_str, val_color, bg_color, txt_color, dim_color)
p = uipanel('Parent', fig, 'Position', pos, 'BackgroundColor', bg_color, ...
    'BorderType', 'line', 'HighlightColor', [0.12 0.16 0.24]);

uicontrol('Parent', p, 'Style', 'text', 'String', title_str, ...
    'Units', 'normalized', 'Position', [0.05 0.70 0.90 0.25], 'ForegroundColor', dim_color, ...
    'BackgroundColor', bg_color, 'FontSize', 8, 'FontWeight', 'bold', 'HorizontalAlignment', 'center');

uicontrol('Parent', p, 'Style', 'text', 'String', val_str, ...
    'Units', 'normalized', 'Position', [0.05 0.30 0.90 0.42], 'ForegroundColor', val_color, ...
    'BackgroundColor', bg_color, 'FontSize', 14, 'FontWeight', 'bold', 'HorizontalAlignment', 'center');

uicontrol('Parent', p, 'Style', 'text', 'String', sub_str, ...
    'Units', 'normalized', 'Position', [0.05 0.05 0.90 0.25], 'ForegroundColor', dim_color, ...
    'BackgroundColor', bg_color, 'FontSize', 7.5, 'HorizontalAlignment', 'center');
end

function s = tern_local(cond, a, b)
if cond, s = a; else, s = b; end
end
